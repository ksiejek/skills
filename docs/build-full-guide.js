#!/usr/bin/env node
// Writes docs/guide.md: MxScout's team guide (public/guide-team.md) with the mendix-docs part
// (docs/guide-mendix-docs.md) added as the next numbered section in each language. Run by sync.sh.
//   node docs/build-full-guide.js <MxScout checkout>
// No dependencies: Node's standard library.
'use strict';
const fs = require('fs');
const path = require('path');
const mx = process.argv[2];
const src = path.join(mx, 'public', 'guide-team.md');
if (!fs.existsSync(src)) { console.log('  note: no ' + src + ' - docs/guide.md left as it is'); process.exit(0); }
const team = fs.readFileSync(src, 'utf8');
const part = fs.readFileSync(path.join(__dirname, 'guide-mendix-docs.md'), 'utf8');
const en = part.split('<!-- en -->')[1].split('<!-- pl -->')[0].trim();
const pl = part.split('<!-- pl -->')[1].trim();
const cut = team.indexOf('\n---\n\n<a id="polski"></a>');
if (cut < 0) throw new Error('guide-team.md: no Polish half');
const head = team.slice(0, cut), tail = team.slice(cut);
const last = (s) => Math.max(0, ...Array.from(s.matchAll(/^### (\d+)\./gm), (m) => Number(m[1])));
const title = '# MxScout & Claude — the full guide · pełny przewodnik\n\n' +
  '> The team\'s copy of this guide ships inside MxScout and is written into each project as `mxscout/GUIDE.md` and, as one page, `mxscout/GUIDE.html`. This full copy adds mendix-docs. Generated by sync.sh — edit MxScout\'s public/guide-team.md or docs/guide-mendix-docs.md, never this file.\n' +
  '> Wersja dla zespołu jest w MxScout i trafia do każdego projektu jako `mxscout/GUIDE.md` oraz, jako jedna strona, `mxscout/GUIDE.html`. Ta pełna wersja dokłada mendix-docs. Generuje ją sync.sh — zmieniaj public/guide-team.md w MxScout albo docs/guide-mendix-docs.md, nigdy ten plik.\n';
const body = head.replace(/^# .*\n/, '').replace(/^\n+/, '\n');
const out = title + body.trimEnd() + '\n\n' + en.replace('{N}', last(head) + 1) + '\n' +
  tail.trimEnd() + '\n\n' + pl.replace('{N}', last(tail) + 1) + '\n';
fs.writeFileSync(path.join(__dirname, 'guide.md'), out);
console.log('docs/guide.md <- ' + src + ' + docs/guide-mendix-docs.md');
